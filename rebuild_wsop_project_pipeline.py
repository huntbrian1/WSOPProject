    fig7 = go.Figure()
    for i, b in enumerate(order):
        sub = sample.loc[sample["entries_bin"].eq(b)]
        fig7.add_trace(go.Scatter(x=sub["skill_pct"], y=sub["realized_cash_rate"], mode="markers",
                                  name=f"{b} entries", marker=dict(color=palette[i], size=6, opacity=0.75)))

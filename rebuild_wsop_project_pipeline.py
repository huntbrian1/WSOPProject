#!/usr/bin/env python3
"""
rebuild_wsop_project_pipeline.py

Rebuilds the WSOP project processed CSVs and chart files from the two Kaggle source datasets.

Core raw inputs:
  1) wsop_main_event_results_1971-2025.csv
     Columns expected: year, place, name, prize, city, state, country, entries, prizepool, buyin, start, finish

  2) wsop_main_event_final_table_2001-2025.csv
     Columns expected: year, entrants, place, name, prize

Optional researched label inputs:
  3) wsop_champion_eventtime_labels_reviewable.csv
  4) wsop_headsup_eventtime_labels_reviewable.csv

Important:
  - The two Kaggle datasets generate the economics panel, reconciliation outputs, heads-up bases,
    headline metrics, chart inputs, and most visualization outputs.
  - Pro/amateur/uncertain labels are NOT present in Kaggle. Those fields require the optional
    researched/reviewable label files.
  - The simulation output is synthetic and generated by code, not derived from Kaggle.

Example:
  python rebuild_wsop_project_pipeline.py \
    --results data/raw/wsop_main_event_results_1971-2025.csv \
    --final-table data/raw/wsop_main_event_final_table_2001-2025.csv \
    --champion-labels data/labels/wsop_champion_eventtime_labels_reviewable.csv \
    --headsup-labels data/labels/wsop_headsup_eventtime_labels_reviewable.csv \
    --output-root .
"""

from __future__ import annotations

